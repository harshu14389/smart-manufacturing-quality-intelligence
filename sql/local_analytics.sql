DROP VIEW IF EXISTS V_DAILY_QUALITY;
CREATE VIEW V_DAILY_QUALITY AS
SELECT DATE_ID, LINE_ID, SHIFT_ID, MODEL_ID,
SUM(INSPECTED_BATCHES) AS INSPECTED_BATCHES,
SUM(FAILED_BATCHES) AS FAILED_BATCHES,
SUM(FIRST_PASS_BATCHES) AS FIRST_PASS_BATCHES,
SUM(PRODUCTION_VOLUME) AS PRODUCTION_VOLUME,
100.0*SUM(FAILED_BATCHES)/NULLIF(SUM(INSPECTED_BATCHES),0) AS DEFECT_RATE_PCT,
100.0*SUM(FIRST_PASS_BATCHES)/NULLIF(SUM(INSPECTED_BATCHES),0) AS FIRST_PASS_YIELD_PCT
FROM FACT_BATCH_QUALITY GROUP BY DATE_ID,LINE_ID,SHIFT_ID,MODEL_ID;
DROP VIEW IF EXISTS V_DAILY_DOWNTIME;
CREATE VIEW V_DAILY_DOWNTIME AS
SELECT DATE_ID,MACHINE_ID,EVENT_CATEGORY,SUM(DOWNTIME_MINUTES) AS DOWNTIME_MINUTES
FROM FACT_DOWNTIME GROUP BY DATE_ID,MACHINE_ID,EVENT_CATEGORY;
