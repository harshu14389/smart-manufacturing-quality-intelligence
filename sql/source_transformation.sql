-- SQLite reference transformation. Aggregate sensors BEFORE joining.
DROP VIEW IF EXISTS V_SOURCE_BATCH;
CREATE VIEW V_SOURCE_BATCH AS
WITH SENSOR_SUMMARY AS (
 SELECT BATCH_ID,
 AVG(CASE WHEN TEMPERATURE_C BETWEEN 10 AND 45 THEN TEMPERATURE_C END) AS TEMPERATURE_C,
 AVG(CASE WHEN HUMIDITY_PCT BETWEEN 0 AND 100 THEN HUMIDITY_PCT END) AS HUMIDITY_PCT,
 AVG(CASE WHEN PRESSURE_BAR BETWEEN 0.5 AND 5 THEN PRESSURE_BAR END) AS PRESSURE_BAR
 FROM RAW_SENSORS GROUP BY BATCH_ID
)
SELECT P.*, S.TEMPERATURE_C, S.HUMIDITY_PCT, S.PRESSURE_BAR,
 I.FAILED, I.DEFECT_CATEGORY, I.INSPECTION_TIME
FROM RAW_PRODUCTION P
LEFT JOIN SENSOR_SUMMARY S ON P.BATCH_ID=S.BATCH_ID
LEFT JOIN RAW_INSPECTIONS I ON P.BATCH_ID=I.BATCH_ID;
-- Downtime stays a separate fact: no unsafe batch-event join.
